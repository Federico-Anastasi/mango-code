// Writes LICENSES/rust-crates.md: license and source of the Rust crates built into the programs of the installer (the
// installer carries the LICENSES folder, prepare-installer.mjs). The list is read from app/Cargo.lock through
// `cargo metadata`, never written by hand.
// Usage: node app/scripts/third-party.mjs            rewrites the file
//        node app/scripts/third-party.mjs --check    exits 1 when the file is not what Cargo.lock gives today
import { execFileSync } from "node:child_process"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

const PLATFORM = "x86_64-pc-windows-msvc"

/** The crates linked into the programs: everything the workspace members depend on for real (not for tests or build scripts). */
export function linkedCrates(metadata) {
  const byId = new Map(metadata.packages.map((p) => [p.id, p]))
  const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]))
  const ours = new Set(metadata.workspace_members)
  const seen = new Set()
  const pending = [...ours]
  while (pending.length) {
    const id = pending.pop()
    if (seen.has(id)) continue
    seen.add(id)
    for (const dep of nodes.get(id).deps) if (dep.dep_kinds.some((k) => k.kind === null)) pending.push(dep.pkg)
  }
  const crates = [...seen].filter((id) => !ours.has(id)).map((id) => byId.get(id))
  for (const c of crates) {
    if (!c.license) throw new Error(`the crate ${c.name} ${c.version} declares no license: read it by hand and decide`)
    if (/GPL|-NC|SEE LICENSE/.test(c.license) && !/ OR /.test(c.license)) throw new Error(`the crate ${c.name} ${c.version} is ${c.license}: it needs a decision before it ships`)
  }
  return crates.sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : a.version < b.version ? -1 : a.version > b.version ? 1 : 0))
}

export function render(crates) {
  const rows = crates.map((c) => `| ${c.name} | ${c.version} | ${c.license} | <${c.repository ?? `https://crates.io/crates/${c.name}`}> |`)
  return [
    "# Rust crates",
    "",
    "Generated by `node app/scripts/third-party.mjs` (not written by hand): the crates built into the programs of the installer, with the license each one declares and where its source is. The license texts are in each crate's repository.",
    "",
    "| Crate | Version | License | Source |",
    "|---|---|---|---|",
    ...rows,
    "",
  ].join("\n")
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
  const file = path.join(app, "..", "LICENSES", "rust-crates.md")
  const metadata = JSON.parse(execFileSync("cargo", ["metadata", "--locked", "--format-version", "1", "--filter-platform", PLATFORM], { cwd: app, encoding: "utf8", maxBuffer: 256 << 20 }))
  const text = render(linkedCrates(metadata))
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text) {
      console.error("LICENSES/rust-crates.md is not up to date: run `node app/scripts/third-party.mjs`")
      process.exit(1)
    }
  } else {
    fs.writeFileSync(file, text)
    console.log(`${file}: ${text.split("\n").length - 7} crates`)
  }
}
