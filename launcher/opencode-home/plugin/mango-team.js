// mango-team.js - links the opencode sessions of a TEAM (separate processes, separate terminals)
// as fixed roles:
//   - MANAGER (cloud, e.g. deepseek): reasons, decides, and gives the instructions.
//   - DEV (local, e.g. 3.6): does the operational work.
//   - AGENTS (cloud, default deepseek on OpenRouter): up to 4, started by the MANAGER when needed,
//     each for its own tasks, and closed by it when no longer needed.
// It is not main -> subagent -> main (Task, off in this project), and it is not a blocking
// exchange either: the sessions are PEERS and INDEPENDENT. Whoever gives an instruction GOES BACK
// to other work AT ONCE; when the other finishes, its summary arrives as an extra message.
//
// COMMUNICATION IS EXPLICIT, IN BOTH DIRECTIONS, AND NOBODY EAVESDROPS ON THE OTHER:
//   - MANAGER -> DEV: tool `ask_dev`. Sends the instruction with promptAsync and returns AT ONCE.
//   - DEV -> MANAGER: tool `ask_manager`. The dev calls it when done (or when it needs a
//     decision) and what it writes reaches the manager as a "[DEV]" message.
//   - MANAGER -> AGENT i: tool `launch_agent` (opens the window, only once) and `ask_agent`
//     (sends the instruction). The agent answers with `ask_manager`, prefixed "[AGENT i]".
//     `close_agent` closes its window (process tree) and frees the slot.
// What does not go through a tool does NOT arrive: the manager does not read the intermediate
// steps, it only sees the messages the others decide to send it.
//
// HOW THEY FIND EACH OTHER, WITHOUT A SEPARATE BRIDGE SERVER:
// opencode already exposes an HTTP server per process (PluginInput.serverUrl) and the SDK can
// send a message without waiting (session.promptAsync). Each side, at its first message, writes
// its OWN session to a file (the port is fixed, mango-code.ps1 sets it):
//   - dev        -> runtime\team-link.json
//   - manager    -> runtime\team-link-manager.json
//   - agent i    -> runtime\team-link-agent-<i>.json
// The other side reads that file and delivers the message: no polling, no reading of the
// history, no blocking wait.
//
// ROLE: decided by MANGO_TEAM_ROLE (env, mango-code.ps1 sets it). Outside the team the variable
// is absent and this plugin does nothing. Agents also carry MANGO_AGENT_ID (1-4).
//
// IN THE APP (Mango Code desktop) the team is the same, with three differences:
//   - the MANAGER is not a separate process: it is the opencode agent `MANGO_TEAM_AGENT` (`team`) in the
//     app's server. The other conversations of the same server are not the team's: the plugin ignores them,
//     and the manager's instructions enter only those of its agent;
//   - dev and agents are HIDDEN `opencode serve` processes that the plugin starts when needed, described by
//     `MANGO_TEAM_LAUNCH` (launch.json), in the manager's project folder;
//   - links and pids live in `MANGO_TEAM_DIR`, in the app's data, not in `<MANGO_HOME>/runtime`
//     (the distribution is read-only).
import { tool } from "@opencode-ai/plugin";
import { createOpencodeClient } from "@opencode-ai/sdk";
import { spawn, spawnSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const ROLE = process.env.MANGO_TEAM_ROLE || "";
const HOME = process.env.MANGO_HOME || "";
const TEAM_DIR = process.env.MANGO_TEAM_DIR || (HOME ? path.join(HOME, "runtime") : "");
const TEAM_AGENT = process.env.MANGO_TEAM_AGENT || "";
// DEV: only one (mango-code -Team: a local dev on the same engine, the whole context for it).
// The dev always writes team-link.json and its replies arrive labeled "[DEV]".
const DEV_LINK = TEAM_DIR ? path.join(TEAM_DIR, "team-link.json") : "";
const MGR_LINK = TEAM_DIR ? path.join(TEAM_DIR, "team-link-manager.json") : "";
const AGENT_ID = process.env.MANGO_AGENT_ID || "";
const AGENT_DIR = process.env.MANGO_AGENT_DIR || (TEAM_DIR ? path.join(TEAM_DIR, "mango-agents") : "");
// 0 is a valid number (the app may have no agents): do not fall back to 4.
const AGENT_MAX = process.env.MANGO_AGENT_MAX ? Number(process.env.MANGO_AGENT_MAX) : 4;
const AGENT_PORTS = (process.env.MANGO_AGENT_PORTS || "4092,4093,4094,4095")
  .split(",")
  .map((s) => Number(s.trim()) || 0);

const AGENT_LABEL = process.env.MANGO_AGENT_LABEL || "cloud model on OpenRouter";
const LAUNCH = process.env.MANGO_TEAM_LAUNCH ? JSON.parse(fs.readFileSync(process.env.MANGO_TEAM_LAUNCH, "utf8")) : null;

const agentLink = (id) => (TEAM_DIR ? path.join(TEAM_DIR, `team-link-agent-${id}.json`) : "");

// --- AN AGENT'S LIFE -----------------------------------------------------------------------
// The agent's window (agent-<i>.ps1, generated by mango-code.ps1) writes its $PID to
// agent-<i>.pid as soon as it starts. It is the root of the powershell -> opencode tree: killing
// it closes the window and everything under it. The PID is also the only way to know whether an
// agent is still ALIVE: the link stays on disk even if the user closes the window by hand.
const agentPidFile = (id) => (AGENT_DIR ? path.join(AGENT_DIR, `agent-${id}.pid`) : "");

function readAgentPid(id) {
  try {
    const pid = Number(fs.readFileSync(agentPidFile(id), "utf8").trim());
    return Number.isInteger(pid) && pid > 0 ? pid : 0;
  } catch { return 0; }
}

function pidAlive(pid) {
  if (!pid) return false;
  try { process.kill(pid, 0); return true; } catch (e) { return e?.code === "EPERM"; }
}

// Who listens on the agent's port: the fallback if the .pid is missing (window opened by an old
// version of the script). Closes opencode but leaves the powershell window (-NoExit).
function pidOnPort(port) {
  const r = spawnSync("netstat", ["-ano", "-p", "tcp"], { encoding: "utf8", windowsHide: true });
  for (const line of (r.stdout || "").split(/\r?\n/)) {
    const c = line.trim().split(/\s+/);
    if (c.length >= 5 && c[3] === "LISTENING" && c[1].endsWith(`:${port}`)) return Number(c[4]) || 0;
  }
  return 0;
}

function killTree(pid) {
  const r = spawnSync("taskkill", ["/PID", String(pid), "/T", "/F"], { encoding: "utf8", windowsHide: true });
  return r.status === 0 ? null : (r.stderr || r.stdout || `taskkill exit ${r.status}`).trim();
}

function forgetAgent(id) {
  for (const f of [agentLink(id), agentPidFile(id)]) {
    try { if (f) fs.rmSync(f, { force: true }); } catch { /* already gone */ }
  }
}

// `extra` carries what is needed to answer that session: in the app the manager is an agent and a model
// (without them, an incoming message would use the defaults), and it has its own project folder.
function writeLink(file, serverUrl, sessionID, extra = {}) {
  try {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, JSON.stringify({ serverUrl: String(serverUrl), sessionID, ...extra }));
  } catch { /* a link that was not written is retried on the next turn, it is not fatal */ }
}

function readLink(file) {
  if (!file || !fs.existsSync(file)) return null;
  try { return JSON.parse(fs.readFileSync(file, "utf8")); } catch { return null; }
}

// Delivers a message to the other session. Returns null if it went through, otherwise the error
// text to show to whoever called the tool.
async function deliver(linkFile, text, who) {
  const link = readLink(linkFile);
  if (!link) {
    return (
      `The ${who} is not connected yet: no message has reached its window yet. ` +
      "Tell the user to write something there (even just 'ready'), then retry."
    );
  }
  const client = createOpencodeClient({ baseUrl: link.serverUrl, directory: link.directory });
  const res = await client.session.promptAsync({
    path: { id: link.sessionID },
    body: { parts: [{ type: "text", text }], ...(link.agent && { agent: link.agent }), ...(link.model && { model: link.model }) },
  });
  if (res.error) return `Could not send the message to the ${who}: ` + JSON.stringify(res.error);
  return null;
}

// Reads the todo list of a session (dev or agent) without sending it any message: `session.todo`
// is a GET, it does not touch the turn of whoever is working. This is how the manager sees how
// far along they are without disturbing them (`read_todos` tool, manager side only).
async function todosOf(linkFile, label) {
  const link = readLink(linkFile);
  if (!link) return `${label}: not connected`;
  try {
    const client = createOpencodeClient({ baseUrl: String(link.serverUrl), directory: link.directory });
    const res = await client.session.todo({ path: { id: link.sessionID } });
    const list = res.data ?? [];
    if (list.length === 0) return `${label}: no todos`;
    const mark = { pending: "[ ]", in_progress: "[~]", completed: "[x]", cancelled: "[-]" };
    return `${label}:\n` + list.map((t) => `  ${mark[t.status] ?? "[?]"} ${t.content}`).join("\n");
  } catch (e) {
    return `${label}: error reading the todos (${e?.message ?? e})`;
  }
}

// The agent that starts writes its link after the first message (the startup --prompt).
// launch_agent waits for it to appear instead of making the manager retry by hand.
async function waitForLink(file, ms) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    if (fs.existsSync(file)) return true;
    await new Promise((r) => setTimeout(r, 500));
  }
  return fs.existsSync(file);
}

// --- HIDDEN DEV AND AGENTS (only in the app: there is a `launch.json`) -----------------------
// In the terminal, dev and agents are windows opened by mango-code.ps1. In the app each one is a windowless
// `opencode serve`, with its own config and data (so its sessions do not end up among the user's
// conversations), working in the manager's project folder. It inherits the app server's environment,
// including the OpenRouter key: it is not in any file. The session is born with a first message, like the
// terminal's `--prompt`: that is what makes it write the link.
const BOOT_DEV =
  "[START] You are the DEV of the team. Do nothing now: reply only with the word ready and wait for instructions from the manager.";
const bootAgent = (n) =>
  `You are AGENT ${n} of the team. You have no memory of other conversations. Tell the manager you are ready ` +
  "with the ask_manager tool (one line only), then wait for its instructions.";

const devPidFile = () => (TEAM_DIR ? path.join(TEAM_DIR, "dev.pid") : "");

function readPidFile(file) {
  try {
    const pid = Number(fs.readFileSync(file, "utf8").trim());
    return Number.isInteger(pid) && pid > 0 ? pid : 0;
  } catch { return 0; }
}

async function waitForHealth(port, ms) {
  const end = Date.now() + ms;
  while (Date.now() < end) {
    try {
      const r = await fetch(`http://127.0.0.1:${port}/global/health`);
      if (r.ok) return true;
    } catch { /* not listening yet */ }
    await new Promise((r) => setTimeout(r, 300));
  }
  return false;
}

// Starts the hidden process of `spec` ({ port, config, xdg }) with the given role and sends it the first message.
// Returns null if it started, otherwise the error text for the model.
async function startHidden({ name, role, id, spec, pidFile, boot, directory }) {
  const env = {
    ...process.env,
    OPENCODE_CONFIG_DIR: spec.config,
    MANGO_TEAM_ROLE: role,
    XDG_DATA_HOME: path.join(spec.xdg, "data"),
    XDG_CONFIG_HOME: path.join(spec.xdg, "config"),
    XDG_CACHE_HOME: path.join(spec.xdg, "cache"),
    XDG_STATE_HOME: path.join(spec.xdg, "state"),
  };
  // The manager is the `team` agent of the app's server: dev and agents are whole processes in their role.
  delete env.MANGO_TEAM_AGENT;
  delete env.MANGO_TEAM_LAUNCH;
  if (id) env.MANGO_AGENT_ID = String(id);
  fs.mkdirSync(path.join(TEAM_DIR, "logs"), { recursive: true });
  const log = fs.openSync(path.join(TEAM_DIR, "logs", `${name}.log`), "a");
  let child;
  try {
    child = spawn(LAUNCH.exe, ["serve", "--hostname", "127.0.0.1", "--port", String(spec.port)], {
      cwd: directory, env, detached: true, stdio: ["ignore", log, log], windowsHide: true,
    });
  } catch (e) {
    return `Could not start ${name}: ${e?.message ?? e}`;
  } finally {
    fs.closeSync(log);
  }
  child.on("error", () => {});
  child.unref();
  fs.mkdirSync(path.dirname(pidFile), { recursive: true });
  fs.writeFileSync(pidFile, String(child.pid));
  if (!(await waitForHealth(spec.port, 30_000))) {
    return `${name} does not respond on port ${spec.port} (log: ${path.join(TEAM_DIR, "logs", name + ".log")}).`;
  }
  const client = createOpencodeClient({ baseUrl: `http://127.0.0.1:${spec.port}`, directory });
  const session = await client.session.create({ body: { title: name } });
  if (session.error) return `${name} started but does not open the session: ` + JSON.stringify(session.error);
  const res = await client.session.promptAsync({
    path: { id: session.data.id },
    body: { parts: [{ type: "text", text: boot }] },
  });
  return res.error ? `${name} started but does not receive the startup message: ` + JSON.stringify(res.error) : null;
}

// A hidden process is ready if it is alive, connected and in this project's folder: if the manager
// works on another project, the old one is closed and restarted in the new one.
function processReady(pidFile, linkFile, directory) {
  const pid = readPidFile(pidFile);
  if (!pidAlive(pid)) return false;
  if (sameFolder(readLink(linkFile)?.directory, directory)) return true;
  killTree(pid);
  return false;
}

const sameFolder = (a, b) => !!a && !!b && path.resolve(a).toLowerCase() === path.resolve(b).toLowerCase();

// In the app the dev starts at the first instruction. Returns null if it is there, otherwise the error for the model.
async function ensureDev(directory) {
  if (!LAUNCH || processReady(devPidFile(), DEV_LINK, directory)) return null;
  fs.rmSync(DEV_LINK, { force: true });
  const err = await startHidden({
    name: "dev", role: "dev", spec: LAUNCH.dev, pidFile: devPidFile(), boot: BOOT_DEV, directory,
  });
  if (err) return err;
  return (await waitForLink(DEV_LINK, 30_000)) ? null : "The dev started but is not connected yet: retry in a few seconds.";
}

// --- THE END-OF-TURN REMINDER ----------------------------------------------------------------
// The real problem, seen in the field: the dev finishes and does NOT call ask_manager, and the
// manager keeps waiting for a message that never comes. opencode emits `session.idle` when the
// turn is over (the model stopped, no tool queued): it is the only reliable signal of "it is
// done". Here, when it arrives, if nobody called ask_manager in this round:
//   1. a synthetic reminder is injected ONCE (`synthetic: true`, so it is not mistaken for a new
//      instruction: see `newTurn`);
//   2. if even after the reminder the turn ends without ask_manager, the manager is notified
//      automatically with the last text - better an automatic summary than silence.
// No loop: `reminderSent` re-arms only on a real (non-synthetic) instruction.
const REMINDER = [
  "Turn finished without a message to the manager.",
  "If the task is complete, or you need a decision or a permission, call the ask_manager tool NOW",
  "with a dense, verifiable summary (what you did, what you checked, the result).",
  "If you are still working, ignore this reminder and continue.",
].join(" ");

async function sendReminder(serverUrl, sessionID) {
  const client = createOpencodeClient({ baseUrl: String(serverUrl) });
  await client.session.promptAsync({
    path: { id: sessionID },
    body: { parts: [{ type: "text", text: REMINDER, synthetic: true }] },
  });
}

// The last NON-synthetic assistant text: it is the summary the dev did not send.
async function lastAssistantText(serverUrl, sessionID) {
  try {
    const client = createOpencodeClient({ baseUrl: String(serverUrl) });
    const res = await client.session.messages({ path: { id: sessionID } });
    const list = res.data ?? [];
    for (let i = list.length - 1; i >= 0; i--) {
      const m = list[i];
      if (m.info?.role !== "assistant") continue;
      const text = (m.parts ?? [])
        .filter((p) => p.type === "text" && !p.synthetic)
        .map((p) => p.text)
        .join("\n")
        .trim();
      if (text) return text.length > 4000 ? text.slice(0, 4000) + "…" : text;
    }
  } catch { /* no text: the manager gets the notice anyway */ }
  return "(no text available)";
}

// Watches the end of the turn of ONE session (dev or agent). `managerLink` is the manager's link where
// the automatic notice arrives; `prefix` is the sender's label.
function watchTurnEnd(serverUrl, managerLink, prefix) {
  let session = "";
  let reported = false;
  let reminderSent = false;
  return {
    newTurn(input, output) {
      session = input.sessionID;
      const parts = output?.parts ?? [];
      // A synthetic part is OUR injection (the reminder or a discipline reminder): it is not a new
      // instruction, so it does not re-arm the round.
      if (parts.length > 0 && parts.every((p) => p.synthetic === true)) return;
      reported = false;
      reminderSent = false;
      // The launcher's startup message ("[START] ...") only serves to connect the window and to
      // warm the prompt cache: it is not a task, so no end-of-turn reminder.
      if (parts.some((p) => p.type === "text" && String(p.text || "").startsWith("[START]"))) reported = true;
    },
    hasReported() {
      reported = true;
    },
    async event({ event }) {
      if (event?.type !== "session.idle") return;
      if (!session || event.properties?.sessionID !== session) return;
      if (reported) return;
      if (!reminderSent) {
        reminderSent = true;
        await sendReminder(serverUrl, session).catch(() => {});
        return;
      }
      reported = true;
      const text = await lastAssistantText(serverUrl, session);
      await deliver(managerLink, `${prefix} (automatic: turn ended without ask_manager)\n${text}`, "manager");
    },
  };
}

export const MangoTeam = async ({ serverUrl, directory }) => {
  if (!ROLE || !HOME) return {};

  // --- DEV: announces itself, and has the tool to talk to the manager -------------------------
  // Every message rewrites the file with the session that is ACTIVE now: if the user opens a new one
  // in the TUI, the link corrects itself on the next turn instead of staying attached to a dead
  // session.
  if (ROLE === "dev") {
    const end = watchTurnEnd(serverUrl, MGR_LINK, "[DEV]");
    return {
      "chat.message": async (input, output) => {
        writeLink(DEV_LINK, serverUrl, input.sessionID, { directory });
        end.newTurn(input, output);
      },
      event: end.event,
      tool: {
        ask_manager: tool({
          description:
            "Sends a message to the MANAGER (separate window) and returns AT ONCE: it does NOT wait. " +
            "ALWAYS call it when you have finished the assigned task, with a dense and verifiable " +
            "summary: what you did, what you checked, the result. Also call it midway if you need a " +
            "decision, a permission or a clarification. It is the ONLY way the manager learns what " +
            "you did: what you do not write here did not happen, as far as it is concerned. Do not " +
            "report intermediate steps, but a complete message that stands on its own.",
          args: {
            message: tool.schema.string().describe("Complete, self-contained summary/request for the manager."),
          },
          async execute({ message }) {
            const err = await deliver(MGR_LINK, "[DEV]\n" + message, "manager");
            if (err) return err;
            end.hasReported();
            return "Message sent to the manager. Continue with the next task, or stop and wait for theirs.";
          },
        }),
      },
    };
  }

  // --- AGENT: like the dev, but with its own identity (1-4) and its own link ------------------
  if (ROLE === "agent") {
    const link = agentLink(AGENT_ID);
    const end = watchTurnEnd(serverUrl, MGR_LINK, `[AGENT ${AGENT_ID}]`);
    return {
      "chat.message": async (input, output) => {
        writeLink(link, serverUrl, input.sessionID, { directory });
        end.newTurn(input, output);
      },
      event: end.event,
      tool: {
        ask_manager: tool({
          description:
            "Sends a message to the MANAGER (separate window) and returns AT ONCE: it does NOT wait. " +
            "ALWAYS call it when you have finished the assigned task, with a dense and verifiable " +
            "summary: what you did, what you checked, the result. Also call it midway if you need a " +
            "decision, a permission or a clarification. It is the ONLY way the manager learns what " +
            "you did. Do not report intermediate steps, but a complete message that stands on its own.",
          args: {
            message: tool.schema.string().describe("Complete, self-contained summary/request for the manager."),
          },
          async execute({ message }) {
            const err = await deliver(MGR_LINK, `[AGENT ${AGENT_ID}]\n` + message, "manager");
            if (err) return err;
            end.hasReported();
            return "Message sent to the manager. Continue with the next task, or stop and wait for theirs.";
          },
        }),
      },
    };
  }

  // --- MANAGER: talks to the dev, and starts/uses up to 4 agents --------------------------------
  if (ROLE === "manager") {
    const launched = new Set();
    // In the app the server also holds the normal conversations: only those of the `team` agent belong to the team.
    const inTeam = (agent) => !TEAM_AGENT || agent === TEAM_AGENT;
    const teamSessions = new Set();
    const managerInstructions = TEAM_AGENT ? fs.readFileSync(path.join(HOME, "opencode-home", "MANGO-manager.md"), "utf8") : "";
    const managerTools = {
        ask_dev: tool({
          description:
            "Sends an instruction to the local DEV (separate window) and returns AT ONCE: it does NOT " +
            "wait for the reply, so after calling this tool continue the conversation with the user " +
            "or think about the next step - do not sit waiting. When the dev finishes, its summary " +
            "will arrive as a separate message, prefixed '[DEV]': it sends it with ask_manager, so " +
            "you will NOT see its intermediate steps. The dev has no memory of THIS conversation: " +
            "write a self-contained instruction (what to do, where, under which constraints).",
          args: {
            instruction: tool.schema.string().describe("Complete, self-contained instruction for the dev."),
          },
          async execute({ instruction }) {
            const failure = await ensureDev(directory);
            if (failure) return failure;
            const err = await deliver(DEV_LINK, instruction, "dev");
            if (err) return err;
            return "Instruction sent to the dev. Feel free to continue: its reply " +
              "will arrive as a '[DEV]' message when it is ready.";
          },
        }),

        launch_agent: tool({
          description:
            `Opens the window of a cloud AGENT (${AGENT_LABEL}), from 1 to ${AGENT_MAX}. ` +
            "Call it ONCE per agent, when you need it: the window stays open and the agent " +
            "announces by itself that it is ready (you will receive an '[AGENT N]' message). It does not block " +
            "the user but waits a few seconds for the agent to connect. Then use `ask_agent` to " +
            "give it tasks, and `close_agent` when it is done. Do not start agents you do not " +
            "need: each one costs OpenRouter tokens.",
          args: {
            agent: tool.schema.string().describe(`Number of the agent to start (1-${AGENT_MAX}).`),
          },
          async execute({ agent }) {
            const n = Number(agent);
            if (!Number.isInteger(n) || n < 1 || n > AGENT_MAX) {
              return `Invalid agent number: choose an integer from 1 to ${AGENT_MAX}.`;
            }
            if (LAUNCH ? processReady(agentPidFile(n), agentLink(n), directory) : pidAlive(readAgentPid(n))) {
              return `Agent ${n} is already open. Use ask_agent to talk to it, or close_agent to close it.`;
            }
            // A window closed by hand leaves its link: clean it, so waitForLink waits for the NEW one.
            forgetAgent(n);
            if (LAUNCH) {
              const err = await startHidden({
                name: `agent-${n}`, role: "agent", id: n, spec: LAUNCH.agents.find((a) => a.id === n),
                pidFile: agentPidFile(n), boot: bootAgent(n), directory,
              });
              if (err) return err;
            } else {
              const script = path.join(AGENT_DIR, `agent-${n}.ps1`);
              if (!AGENT_DIR || !fs.existsSync(script)) {
                return `Cannot find agent ${n}'s script (${script}). Restart mango-code -Team.`;
              }
              try {
                // `cmd /c start` is the only reliable way to open a NEW window from a process
                // running in another console (a plain spawn would inherit it).
                const child = spawn("cmd", ["/c", "start", "", "powershell", "-NoExit", "-File", script], {
                  detached: true,
                  stdio: "ignore",
                  windowsHide: false,
                });
                child.unref();
              } catch (e) {
                return `Could not open agent ${n}'s window: ${e?.message ?? e}`;
              }
            }
            launched.add(n);
            const connected = await waitForLink(agentLink(n), 25_000);
            const port = AGENT_PORTS[n - 1] || "?";
            if (!connected) {
              return (
                `Agent ${n} started (port ${port}), but is not connected yet. ` +
                "Look at its window: if it is stuck on a question, answer there. Retry ask_agent shortly."
              );
            }
            return `Agent ${n} started and connected (port ${port}). You can now use ask_agent ${n} to give it a task.`;
          },
        }),

        ask_agent: tool({
          description:
            "Sends an instruction to an AGENT already started with `launch_agent` and returns AT " +
            "ONCE: it does NOT wait for the reply. The reply will arrive by itself as a message prefixed " +
            "'[AGENT N]'. The agent has no memory of this conversation: write a self-contained " +
            "instruction (what to do, where, under which constraints). Do not start it again: if it is " +
            "not connected, use launch_agent first.",
          args: {
            agent: tool.schema.string().describe(`Number of the agent (1-${AGENT_MAX}).`),
            instruction: tool.schema.string().describe("Complete, self-contained instruction for the agent."),
          },
          async execute({ agent, instruction }) {
            const n = Number(agent);
            if (!Number.isInteger(n) || n < 1 || n > AGENT_MAX) {
              return `Invalid agent number: choose an integer from 1 to ${AGENT_MAX}.`;
            }
            const pid = readAgentPid(n);
            if (pid && !pidAlive(pid)) {
              forgetAgent(n);
              return `Agent ${n} was closed (its window is gone). Reopen it with launch_agent ${n}.`;
            }
            if (!readLink(agentLink(n))) {
              return (
                `Agent ${n} is not connected. Start it with launch_agent ${n}, or wait for its ` +
                "ready message. If its window was opened a moment ago, retry in a few seconds."
              );
            }
            const err = await deliver(agentLink(n), "[MANAGER]\n" + instruction, `agent ${n}`);
            if (err) return err;
            return `Instruction sent to agent ${n}. Its reply will arrive as an '[AGENT ${n}]' message.`;
          },
        }),

        list_agents: tool({
          description:
            "Shows the state of the agents (started, connected, not started) and their port. " +
            "Use it to know who is already there before starting more.",
          args: {},
          async execute() {
            const lines = [];
            for (let i = 1; i <= AGENT_MAX; i++) {
              const alive = pidAlive(readAgentPid(i));
              const link = readLink(agentLink(i));
              const state = alive
                ? (link ? "connected" : "started, not connected yet")
                : launched.has(i) || link
                  ? "closed (window no longer open)"
                  : "not started";
              lines.push(`agent ${i}: ${state} (port ${AGENT_PORTS[i - 1] || "?"})`);
            }
            return lines.join("\n");
          },
        }),

        read_todos: tool({
          description:
            "Shows the todo list of the DEV and of every open AGENT, without sending any message: " +
            "it is a read, it does not disturb them and does not use up their turn. Use it to see " +
            "how far along they are, who is stuck and what remains. Every task you assign must ask to keep this " +
            "list updated with `todowrite`.",
          args: {},
          async execute() {
            const out = [await todosOf(DEV_LINK, "DEV")];
            for (let i = 1; i <= AGENT_MAX; i++) {
              if (!pidAlive(readAgentPid(i))) continue;
              out.push(await todosOf(agentLink(i), `AGENT ${i}`));
            }
            return out.join("\n");
          },
        }),

        close_agent: tool({
          description:
            "Closes an AGENT: ends its process and its window and frees the slot (it can be " +
            "reopened with launch_agent, but starts from zero). Use it when the agent has finished its " +
            "task and is no longer needed, or if it is stuck. What it is doing is interrupted: if you " +
            "need its result, first wait for its '[AGENT N]' message.",
          args: {
            agent: tool.schema.string().describe(`Number of the agent to close (1-${AGENT_MAX}).`),
          },
          async execute({ agent }) {
            const n = Number(agent);
            if (!Number.isInteger(n) || n < 1 || n > AGENT_MAX) {
              return `Invalid agent number: choose an integer from 1 to ${AGENT_MAX}.`;
            }
            let pid = readAgentPid(n);
            let hadWindow = true;
            if (!pidAlive(pid)) {
              pid = pidOnPort(AGENT_PORTS[n - 1]);
              hadWindow = false;
            }
            launched.delete(n);
            if (!pid) {
              forgetAgent(n);
              return `Agent ${n} is not open: nothing to close.`;
            }
            const err = killTree(pid);
            if (err && pidAlive(pid)) return `Could not close agent ${n} (PID ${pid}): ${err}`;
            forgetAgent(n);
            return hadWindow
              ? `Agent ${n} closed (window and process). The slot is free.`
              : `Agent ${n} closed (opencode on port ${AGENT_PORTS[n - 1]}); its powershell window ` +
                "may stay open: it has to be closed by hand.";
          },
        }),
    };
    // Without agents (the app may have 0) their tools are useless, and each one weighs on the prompt at every turn.
    if (AGENT_MAX === 0) for (const name of ["launch_agent", "ask_agent", "list_agents", "close_agent"]) delete managerTools[name];
    return {
      "chat.message": async (input) => {
        if (!inTeam(input.agent)) return;
        teamSessions.add(input.sessionID);
        writeLink(MGR_LINK, serverUrl, input.sessionID, { directory, agent: input.agent, model: input.model });
      },
      "experimental.chat.system.transform": async (input, output) => {
        if (TEAM_AGENT && teamSessions.has(input.sessionID)) output.system.push(managerInstructions);
      },
      tool: managerTools,
    };
  }

  return {};
};
